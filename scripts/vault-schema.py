#!/usr/bin/env python3
"""Generate src/vault/schema.gen.ts from the vault's tag schemas (T-335 one reader).

The vault declares each kind the app reads (task, decision, card, run, node, draft) as a tag with fields; this writes their
names, types and enums (never the descriptions: this repo is public) as TypeScript, so the reader's types come from the vault.

  python3 scripts/vault-schema.py tags.json          # from a saved copy: {"task": {"fields": {...}, "parent_names": [...]}, ...}
  UNI_VAULT_API=http://127.0.0.1:1940/vault/uni/api/ UNI_VAULT_TOKEN_FILE=~/token python3 scripts/vault-schema.py   # read-only GETs
  python3 scripts/vault-schema.py --check tags.json  # exit 1 when the committed file differs (CI-free drift check)
"""
import json, os, sys, urllib.request

KINDS = ['task', 'decision', 'card', 'run', 'node', 'draft']
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'vault', 'schema.gen.ts')
TS = {'string': 'string', 'date': 'string', 'reference': 'string', 'boolean': 'boolean', 'integer': 'number', 'number': 'number',
      'array': 'unknown[]', 'object': 'Record<string, unknown>'}


def fetch():
    base = os.environ.get('UNI_VAULT_API', 'http://127.0.0.1:1940/vault/uni/api/')
    tok = open(os.path.expanduser(os.environ['UNI_VAULT_TOKEN_FILE'])).read().split()[-1]
    out = {}
    for k in KINDS:
        req = urllib.request.Request(base + 'tags/' + k, headers={'Authorization': 'Bearer ' + tok})
        with urllib.request.urlopen(req, timeout=30) as r:
            t = json.load(r)
        out[k] = {'fields': t.get('fields') or {}, 'parent_names': t.get('parent_names') or []}
    return out


def render(tags):
    L = ['// Generated by scripts/vault-schema.py from the vault\'s tag schemas: do not edit by hand. Names, types and enums only.', '']
    L.append('export const SCHEMA = {')
    for k in KINDS:
        L.append(f'  {json.dumps(k)}: {{')
        for name, f in sorted((tags[k].get('fields') or {}).items()):
            spec = {'type': f.get('type', 'string')}
            if f.get('enum'):
                spec['enum'] = f['enum']
            if f.get('indexed'):
                spec['indexed'] = True
            L.append(f'    {json.dumps(name)}: {json.dumps(spec)},')
        L.append('  },')
    L.append('} as const;')
    L.append('')
    L.append('/** The tags each kind is declared under (a decision is a task too). */')
    L.append('export const PARENTS: Record<keyof typeof SCHEMA, readonly string[]> = ' + json.dumps({k: tags[k].get('parent_names') or [] for k in KINDS}) + ';')
    L.append('')
    for k in KINDS:
        name = ''.join(p.capitalize() for p in k.split('-')) + 'Meta'
        L.append(f'/** A `{k}` note\'s metadata as the vault declares it (every field optional: a note carries what its writer set). */')
        L.append(f'export type {name} = {{')
        for fname, f in sorted((tags[k].get('fields') or {}).items()):
            t = ' | '.join(json.dumps(e) for e in f['enum']) if f.get('enum') else TS.get(f.get('type', 'string'), 'unknown')
            L.append(f'  {json.dumps(fname)}?: {t} | null;')
        L.append('};')
    L.append('')
    L.append('/** Metadata by kind. */')
    L.append('export type Meta = { ' + ' '.join(f'{json.dumps(k)}: {"".join(p.capitalize() for p in k.split("-"))}Meta;' for k in KINDS) + ' };')
    return '\n'.join(L) + '\n'


def main(argv):
    check = '--check' in argv
    files = [a for a in argv if not a.startswith('--')]
    tags = json.load(open(files[0])) if files else fetch()
    text = render(tags)
    if check:
        same = os.path.exists(OUT) and open(OUT).read() == text
        print('schema.gen.ts is current' if same else 'schema.gen.ts differs from the vault: run scripts/vault-schema.py')
        return 0 if same else 1
    open(OUT, 'w').write(text)
    print(f'wrote {os.path.relpath(OUT)} ({sum(len(tags[k].get("fields") or {}) for k in KINDS)} fields, {len(KINDS)} kinds)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
